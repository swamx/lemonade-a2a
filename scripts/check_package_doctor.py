"""Package smoke gate: tolerate only an untested, in-range A2A SDK warning.

All other doctor warnings, unknown checks and failures block packaging.
The compatibility manifest is still generated by the canary; this does not change
doctor's documented exit codes or strict startup behavior.
"""
from __future__ import annotations

import json
import subprocess
import sys


def acceptable(report: dict) -> bool:
    checks = report.get("checks")
    if not isinstance(checks, list) or not checks:
        return False
    for check in checks:
        if check.get("verdict") == "pass":
            continue
        if not (
            check.get("id") == "a2a_sdk"
            and check.get("verdict") == "warn"
            and "inside the declared range" in check.get("detail", "")
            and "not tested" in check.get("detail", "")
        ):
            return False
    return True


def main() -> int:
    binary = sys.argv[1] if len(sys.argv) > 1 else "lemonade-a2a"
    result = subprocess.run(
        [binary, "doctor", "--no-lemonade", "--sdk-gap", "--json"],
        capture_output=True,
        text=True,
        check=False,
    )
    try:
        report = json.loads(result.stdout)
    except json.JSONDecodeError:
        print(f"doctor emitted invalid JSON: {result.stderr or result.stdout}", file=sys.stderr)
        return 1
    for check in report.get("checks", []):
        print(f"{check.get('id')}: {check.get('verdict')} — {check.get('detail')}")
    if result.returncode not in (0, 1) or not acceptable(report):
        print(f"package doctor gate FAILED (doctor exit {result.returncode})", file=sys.stderr)
        return 1
    print("package doctor gate PASS; unknown compatible SDK versions are canary-owned")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
